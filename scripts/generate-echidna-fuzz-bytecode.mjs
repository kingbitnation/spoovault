/**
 * Embeds unlinked SpooVault creation bytecode + library patch offsets for the
 * Echidna/Medusa harness. Re-run after SpooVault or library bytecode changes:
 *   npx hardhat compile && node scripts/generate-echidna-fuzz-bytecode.mjs
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const ARTIFACT = path.join(
  ROOT,
  "artifacts/contracts/SpooVault.sol/SpooVault.json"
);
const VRF_LIB_ARTIFACT = path.join(
  ROOT,
  "artifacts/contracts/libraries/EmergencyVrfLogic.sol/EmergencyVrfLogic.json"
);
const ADMIN_LIB_ARTIFACT = path.join(
  ROOT,
  "artifacts/contracts/libraries/SpooVaultAdminLogic.sol/SpooVaultAdminLogic.json"
);
const OUT = path.join(ROOT, "fuzz/harness/SpooVaultFuzzBytecode.sol");

function normalizeBytecode(bytecode, linkReferences) {
  let hex = bytecode.startsWith("0x") ? bytecode.slice(2) : bytecode;
  const slots = [];
  for (const file of Object.keys(linkReferences || {})) {
    for (const name of Object.keys(linkReferences[file])) {
      for (const loc of linkReferences[file][name]) {
        slots.push({ start: loc.start * 2, length: loc.length * 2 });
      }
    }
  }
  slots.sort((a, b) => b.start - a.start);
  for (const slot of slots) {
    hex =
      hex.slice(0, slot.start) +
      "0".repeat(slot.length) +
      hex.slice(slot.start + slot.length);
  }
  if (!/^[0-9a-fA-F]*$/i.test(hex)) {
    const bad = hex.search(/[^0-9a-fA-F]/i);
    throw new Error(
      `Bytecode still contains non-hex data after link-slot normalization (index ${bad})`
    );
  }
  return hex;
}

function toSolHex(bytecode, linkReferences) {
  const hex = normalizeBytecode(bytecode, linkReferences);
  const chunks = hex.match(/.{1,4096}/g) ?? [];
  return chunks.map((c) => `hex"${c}"`).join("\n        ");
}

function toLinkLines(offsets, libVar) {
  return offsets
    .map(
      (offset) =>
        `        creationCode = BytecodeLibraryLinker.linkAt(creationCode, ${offset}, ${libVar});`
    )
    .join("\n");
}

function readArtifact(filePath) {
  if (!fs.existsSync(filePath)) {
    console.error(`Missing artifact: ${filePath}\nRun: npx hardhat compile`);
    process.exit(1);
  }
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function main() {
  const artifact = readArtifact(ARTIFACT);
  const vrfLibArtifact = readArtifact(VRF_LIB_ARTIFACT);
  const adminLibArtifact = readArtifact(ADMIN_LIB_ARTIFACT);
  const vrfOffsets =
    artifact.linkReferences?.["contracts/libraries/EmergencyVrfLogic.sol"]
      ?.EmergencyVrfLogic?.map((loc) => loc.start) ?? [];
  const adminOffsets =
    artifact.linkReferences?.["contracts/libraries/SpooVaultAdminLogic.sol"]
      ?.SpooVaultAdminLogic?.map((loc) => loc.start) ?? [];

  if (vrfOffsets.length === 0 || adminOffsets.length === 0) {
    console.error("SpooVault artifact has no library link references.");
    process.exit(1);
  }

  const contents = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

import "./BytecodeLibraryLinker.sol";

// AUTO-GENERATED by scripts/generate-echidna-fuzz-bytecode.mjs — do not edit.
library SpooVaultFuzzBytecode {
    bytes internal constant VRF_LOGIC_CREATION =
        ${toSolHex(vrfLibArtifact.bytecode, vrfLibArtifact.linkReferences)};

    bytes internal constant ADMIN_LOGIC_CREATION =
        ${toSolHex(adminLibArtifact.bytecode, adminLibArtifact.linkReferences)};

    bytes internal constant SPOOVAULT_UNLINKED =
        ${toSolHex(artifact.bytecode, artifact.linkReferences)};

    function deployEmergencyVrfLogic() internal returns (address) {
        return BytecodeLibraryLinker.deploy(VRF_LOGIC_CREATION);
    }

    function deploySpooVaultAdminLogic() internal returns (address) {
        return BytecodeLibraryLinker.deploy(ADMIN_LOGIC_CREATION);
    }

    function deployLinkedVault(address vrfLib, address adminLib) internal returns (address) {
        bytes memory creationCode = SPOOVAULT_UNLINKED;
${toLinkLines(vrfOffsets, "vrfLib")}
${toLinkLines(adminOffsets, "adminLib")}
        return BytecodeLibraryLinker.deploy(creationCode);
    }
}
`;

  fs.writeFileSync(OUT, contents);
  console.log(`Wrote ${path.relative(ROOT, OUT)}`);
}

main();
