/**
 * Embeds unlinked SpooVault creation bytecode + library patch offsets for the
 * Echidna/Medusa harness. Re-run after SpooVault or library bytecode changes:
 *   npx hardhat compile && node scripts/generate-echidna-fuzz-bytecode.mjs
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const ARTIFACT = path.join(
  ROOT,
  "artifacts/contracts/SpooVault.sol/SpooVault.json"
);
const OUT = path.join(ROOT, "fuzz/harness/SpooVaultFuzzBytecode.sol");

function toSolHex(bytecode) {
  const hex = bytecode.startsWith("0x") ? bytecode.slice(2) : bytecode;
  const chunks = hex.match(/.{1,4096}/g) ?? [];
  return chunks.map((c) => `hex"${c}"`).join("\n        ");
}

function toOffsetArray(name, offsets) {
  const values = offsets.map((o) => `        ${o}`).join(",\n");
  return `    uint256[${offsets.length}] internal constant ${name} = [\n${values}\n    ];`;
}

function main() {
  if (!fs.existsSync(ARTIFACT)) {
    console.error("Missing SpooVault artifact. Run: npx hardhat compile");
    process.exit(1);
  }

  const artifact = JSON.parse(fs.readFileSync(ARTIFACT, "utf8"));
  const vrfOffsets =
    artifact.linkReferences?.["contracts/libraries/EmergencyVrfLogic.sol"]
      ?.EmergencyVrfLogic?.map((loc) => loc.start) ?? [];
  const adminOffsets =
    artifact.linkReferences?.["contracts/libraries/SpooVaultAdminLogic.sol"]
      ?.SpooVaultAdminLogic?.map((loc) => loc.start) ?? [];

  if (vrfOffsets.length === 0 || adminOffsets.length === 0) {
    console.error("SpooVault artifact has no library link references.");
    process.exit(1);
  }

  const contents = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

import "./BytecodeLibraryLinker.sol";

// AUTO-GENERATED by scripts/generate-echidna-fuzz-bytecode.mjs — do not edit.
library SpooVaultFuzzBytecode {
    bytes internal constant SPOOVAULT_UNLINKED =
        ${toSolHex(artifact.bytecode)};

${toOffsetArray("VRF_LIBRARY_OFFSETS", vrfOffsets)}

${toOffsetArray("ADMIN_LIBRARY_OFFSETS", adminOffsets)}

    function deployLinkedVault(address vrfLib, address adminLib) internal returns (address) {
        bytes memory creationCode = SPOOVAULT_UNLINKED;
        for (uint256 i = 0; i < VRF_LIBRARY_OFFSETS.length; i++) {
            creationCode = BytecodeLibraryLinker.linkAt(creationCode, VRF_LIBRARY_OFFSETS[i], vrfLib);
        }
        for (uint256 i = 0; i < ADMIN_LIBRARY_OFFSETS.length; i++) {
            creationCode = BytecodeLibraryLinker.linkAt(creationCode, ADMIN_LIBRARY_OFFSETS[i], adminLib);
        }
        return BytecodeLibraryLinker.deploy(creationCode);
    }
}
`;

  fs.writeFileSync(OUT, contents);
  console.log(`Wrote ${path.relative(ROOT, OUT)}`);
}

main();
